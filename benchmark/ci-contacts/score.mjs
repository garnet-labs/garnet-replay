#!/usr/bin/env node
// Score every run under benchmark/ci-contacts/runs/<model>/<track>/ and write results.md.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs"

import { scoreAnswer, summarize, TRACKS } from "../../lib/ci-contacts.mjs"

const tasks = JSON.parse(readFileSync("benchmark/ci-contacts/tasks.json", "utf8"))
const root = "benchmark/ci-contacts/runs"
const models = existsSync(root) ? readdirSync(root).sort() : []
const pct = (x) => (x === null ? "—" : `${Math.round(x * 100)}%`)

const summaries = []
const perTask = []
for (const model of models) {
  for (const track of TRACKS) {
    const dir = `${root}/${model}/${track}`
    if (!existsSync(dir)) {
      continue
    }
    const rows = []
    for (const task of tasks) {
      const file = `${dir}/${task.id}.json`
      if (!existsSync(file)) {
        continue
      }
      const run = JSON.parse(readFileSync(file, "utf8"))
      const score = scoreAnswer(task.key, run.answer)
      rows.push({ task, score })
      perTask.push({ model, track, id: task.id, verdict: run.answer.verdict, outcome: score.outcome, named: run.answer.new_destinations })
    }
    summaries.push({ model, track, s: summarize(rows) })
  }
}

const lines = [
  "# CI Contacts results",
  "",
  "Generated by `node benchmark/ci-contacts/score.mjs` from `benchmark/ci-contacts/runs/`. Task card: `benchmark/ci-contacts/README.md`.",
  "",
  "| model | track | tasks | hidden flagged | hidden said clean | hidden: named a destination | visible flagged | clean claimed without support | false alarms | dest precision | dest recall | runner-infra named | invalid |",
  "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
]
for (const { model, track, s } of summaries) {
  lines.push(`| ${model} | ${track} | ${s.tasks} | ${s.hidden_flagged}/${s.hidden_tasks} | ${s.hidden_said_clean}/${s.hidden_tasks} | ${s.hidden_named_destination}/${s.hidden_tasks} | ${s.visible_flagged}/${s.visible_tasks} | ${s.overclaimed_clean}/${s.unsupported_tasks} | ${s.false_alarms} | ${pct(s.destination_precision)} | ${pct(s.destination_recall)} | ${s.background_fp} | ${s.invalid} |`)
}
lines.push("", "## Per task (hidden and visible new-behavior tasks)", "", "| task | model | track | verdict | outcome | destinations named |", "|---|---|---|---|---|---|")
const interesting = new Set(tasks.filter((t) => t.key.expected_verdict === "new-behavior").map((t) => t.id))
for (const r of perTask.filter((r) => interesting.has(r.id)).sort((a, b) => a.id.localeCompare(b.id) || a.model.localeCompare(b.model) || a.track.localeCompare(b.track))) {
  lines.push(`| ${r.id} | ${r.model} | ${r.track} | ${r.verdict} | ${r.outcome} | ${r.named.join(", ") || "—"} |`)
}
writeFileSync("benchmark/ci-contacts/results.md", `${lines.join("\n")}\n`)
console.log(lines.slice(4, 5 + summaries.length).join("\n"))
